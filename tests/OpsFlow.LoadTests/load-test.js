import http from 'k6/http';
import { check } from 'k6';
import { Counter, Rate, Trend } from 'k6/metrics';
import encoding from 'k6/encoding';

const baseUrl = (__ENV.BASE_URL || 'http://host.docker.internal:5153').replace(/\/$/, '');
const email = __ENV.ADMIN_EMAIL || 'admin@acmetech.io';
const password = __ENV.ADMIN_PASSWORD || 'Admin@1234!';

const servicesRequests = new Counter('services_requests');
const servicesErrors = new Rate('services_errors');
const servicesLatency = new Trend('services_latency', true);
const incidentsRequests = new Counter('incidents_requests');
const incidentsErrors = new Rate('incidents_errors');
const incidentsLatency = new Trend('incidents_latency', true);
const createRequests = new Counter('create_incident_requests');
const createErrors = new Rate('create_incident_errors');
const createLatency = new Trend('create_incident_latency', true);

export const options = {
  scenarios: {
    services_browse: { executor: 'constant-vus', exec: 'getServices', vus: 100, duration: '30s' },
    incidents_browse: { executor: 'constant-vus', exec: 'getIncidents', vus: 50, duration: '30s' },
    incident_create: { executor: 'constant-vus', exec: 'createIncident', vus: 10, duration: '30s' },
  },
  thresholds: {
    services_errors: ['rate<0.01'],
    incidents_errors: ['rate<0.01'],
    create_incident_errors: ['rate<0.01'],
  },
  summaryTrendStats: ['avg', 'min', 'med', 'max', 'p(50)', 'p(90)', 'p(95)', 'p(99)'],
};

export function setup() {
  const login = http.post(`${baseUrl}/api/auth/login`, JSON.stringify({ email, password }), {
    headers: { 'Content-Type': 'application/json' },
  });
  check(login, { 'admin login succeeds': (response) => response.status === 200 });
  if (login.status !== 200) {
    throw new Error(`Admin login failed (${login.status}): ${login.body}`);
  }

  const accessToken = login.json('accessToken');
  const payload = JSON.parse(encoding.b64decode(accessToken.split('.')[1], 'rawurl', 's'));
  const organizationId = payload.orgId;
  const headers = { Authorization: `Bearer ${accessToken}` };
  const servicesResponse = http.get(`${baseUrl}/api/organizations/${organizationId}/services`, { headers });
  check(servicesResponse, { 'services setup request succeeds': (response) => response.status === 200 });
  if (servicesResponse.status !== 200) {
    throw new Error(`Loading services failed (${servicesResponse.status}): ${servicesResponse.body}`);
  }
  const services = servicesResponse.json();
  if (!services || services.length === 0) {
    throw new Error('The seeded organization has no services for the load test.');
  }

  return { accessToken, organizationId, serviceId: services[0].id };
}

export function getServices(data) {
  const response = http.get(`${baseUrl}/api/organizations/${data.organizationId}/services`, {
    headers: { Authorization: `Bearer ${data.accessToken}` },
    tags: { operation: 'services' },
  });
  servicesRequests.add(1);
  servicesErrors.add(response.status !== 200);
  servicesLatency.add(response.timings.duration);
  check(response, { 'GET services returns 200': (result) => result.status === 200 });
}

export function getIncidents(data) {
  const response = http.get(`${baseUrl}/api/organizations/${data.organizationId}/incidents`, {
    headers: { Authorization: `Bearer ${data.accessToken}` },
    tags: { operation: 'incidents' },
  });
  incidentsRequests.add(1);
  incidentsErrors.add(response.status !== 200);
  incidentsLatency.add(response.timings.duration);
  check(response, { 'GET incidents returns 200': (result) => result.status === 200 });
}

export function createIncident(data) {
  const payload = JSON.stringify({
    title: `k6 load test ${__VU}-${__ITER}`,
    description: 'Incident generated by the OpsFlow Phase 8 local load test.',
    severity: 'Low',
    serviceId: data.serviceId,
  });
  const response = http.post(`${baseUrl}/api/organizations/${data.organizationId}/incidents`, payload, {
    headers: { Authorization: `Bearer ${data.accessToken}`, 'Content-Type': 'application/json' },
    tags: { operation: 'create_incident' },
  });
  createRequests.add(1);
  createErrors.add(response.status !== 201);
  createLatency.add(response.timings.duration);
  check(response, { 'POST incident returns 201': (result) => result.status === 201 });
}
